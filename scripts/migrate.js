// scripts/migrate.js
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import "dotenv/config";
import { initDb, getConnection, closeDb } from "../src/config/db.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function migrate() {
  await initDb();
  const connection = await getConnection();

  try {
    await connection.execute(`
      BEGIN
        EXECUTE IMMEDIATE '
          CREATE TABLE DB_MIGRATIONS (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            NAME VARCHAR2(255) PRIMARY KEY,
            APPLIED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
          )
        ';
      EXCEPTION
        WHEN OTHERS THEN
          IF SQLCODE != -955 THEN RAISE; END IF;
      END;
    `);

    const dir = path.join(__dirname, "../db/migrations");

    const files = fs
      .readdirSync(dir)
      .filter((file) => file.endsWith(".sql"))
      .sort();

    for (const file of files) {
      const result = await connection.execute(
        `SELECT COUNT(*) AS COUNT
         FROM DB_MIGRATIONS
         WHERE NAME = :name`,
        { name: file }
      );

      if (result.rows[0][0] > 0) {
        continue;
      }

      const sql = fs.readFileSync(path.join(dir, file), "utf8");

      // Split on ';' at statement boundaries so a migration file can hold
      // multiple DDL statements (CREATE TABLE, CREATE INDEX, etc). PL/SQL
      // blocks (trigger bodies ending in '/') are executed as one unit.
      const statements = splitStatements(sql);

      console.log(`Running ${file}`);

      for (const stmt of statements) {
        if (!stmt.trim()) continue;
        await connection.execute(stmt);
      }

      await connection.execute(
        `INSERT INTO DB_MIGRATIONS (NAME)
         VALUES (:name)`,
        { name: file }
      );

      await connection.commit();
      console.log(`Applied ${file}`);
    }

    console.log("Migrations complete");
  } catch (err) {
    await connection.rollback();
    throw err;
  } finally {
    await connection.close();
    await closeDb();
  }
}

/**
 * Splits a .sql file into individual executable statements.
 * - Plain statements are split on ';'
 * - PL/SQL blocks (CREATE OR REPLACE TRIGGER/PROCEDURE/FUNCTION ... END; /)
 *   are kept whole and terminated by a standalone '/' line.
 */
function splitStatements(sql) {
  const lines = sql.split("\n");
  const statements = [];
  let buffer = [];
  let inPlsqlBlock = false;

  for (const line of lines) {
    const trimmed = line.trim();

    if (!inPlsqlBlock && /^(CREATE\s+OR\s+REPLACE\s+)?(TRIGGER|PROCEDURE|FUNCTION|PACKAGE)\b/i.test(trimmed)) {
      inPlsqlBlock = true;
    }

    if (inPlsqlBlock) {
      if (trimmed === "/") {
        statements.push(buffer.join("\n").trim());
        buffer = [];
        inPlsqlBlock = false;
      } else {
        buffer.push(line);
      }
      continue;
    }

    buffer.push(line);
    // naive but fine for DDL: split on ';' that ends a statement line
    if (trimmed.endsWith(";") && !trimmed.startsWith("--")) {
      const stmt = buffer.join("\n").trim().replace(/;$/, "");
      if (stmt) statements.push(stmt);
      buffer = [];
    }
  }

  const rest = buffer.join("\n").trim();
  if (rest) statements.push(rest.replace(/;$/, ""));

  return statements;
}

migrate().catch((err) => {
  console.error("Migration failed:", err);
  process.exit(1);
});