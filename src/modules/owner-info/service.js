/**
 * GET all owner info rows, joining PM_PROJECT for project name.
 */
export async function getAllOwnerInfo() {
  const sql = `
    SELECT
      oi.ID,
      oi.O_NAME,
      oi.ADDRESS,
      oi.SUBURB,
      oi.POSTCODE,
      oi.STATE,
      oi.EMAIL,
      oi.PHONE,
      oi.PROJECT_ID,
      p.P_NAME   AS PROJECT_NAME,
      oi.CREATED_BY,
      oi.UPDATED_BY,
      oi.ENTRY_DATE,
      oi.UPDATED_DATE
    FROM PM_OWNER_INFO oi
    LEFT JOIN PM_PROJECT p ON p.P_ID = oi.PROJECT_ID
    ORDER BY oi.ID
  `;
  const result = await poolExecute(sql, {}, { outFormat: oracledb.OUT_FORMAT_OBJECT });
  return result.rows;
}

