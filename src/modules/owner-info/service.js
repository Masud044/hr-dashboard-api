/**
 * CREATE a new PM_OWNER_INFO row.
 * ID is generated by a sequence — adjust SEQ name to match your DB.
 */
export async function createOwnerInfo(data) {
  const {
    oName,
    address,
    suburb,
    postcode,
    state,
    email,
    phone,
    projectId,
    createdBy,
    updatedBy,
  } = data;

  const sql = `
    INSERT INTO PM_OWNER_INFO (
      
      O_NAME,
      ADDRESS,
      SUBURB,
      POSTCODE,
      STATE,
      EMAIL,
      PHONE,
      PROJECT_ID,
      CREATED_BY,
      UPDATED_BY,
      ENTRY_DATE,
      UPDATED_DATE
    ) VALUES (
      
      :oName,
      :address,
      :suburb,
      :postcode,
      :state,
      :email,
      :phone,
      :projectId,
      :createdBy,
      :updatedBy,
      SYSDATE,
      SYSDATE
    )
    RETURNING ID INTO :newId
  `;

  const binds = {
    oName:     oName     ?? null,
    address:   address   ?? null,
    suburb:    suburb    ?? null,
    postcode:  postcode  ?? null,
    state:     state     ?? null,
    email:     email     ?? null,
    phone:     phone     ?? null,
    projectId: projectId ?? null,
    createdBy: createdBy ?? null,
    updatedBy: updatedBy ?? null,
    newId: { dir: oracledb.BIND_OUT, type: oracledb.NUMBER },
  };

  const result = await poolExecute(sql, binds, { autoCommit: true });
  return { id: result.outBinds.newId[0] };
}

/**
 * UPDATE an existing PM_OWNER_INFO row.
 */
export async function updateOwnerInfo(id, data) {
  const {
    oName,
    address,
    suburb,
    postcode,
    state,
    email,
    phone,
    projectId,
    updatedBy,
  } = data;

  const sql = `
    UPDATE PM_OWNER_INFO
    SET
      O_NAME       = :oName,
      ADDRESS      = :address,
      SUBURB       = :suburb,
      POSTCODE     = :postcode,
      STATE        = :state,
      EMAIL        = :email,
      PHONE        = :phone,
      PROJECT_ID   = :projectId,
      UPDATED_BY   = :updatedBy,
      UPDATED_DATE = SYSDATE
    WHERE ID = :id
  `;

  const result = await poolExecute(
    sql,
    { oName, address, suburb, postcode, state, email, phone, projectId, updatedBy, id },
    { autoCommit: true }
  );
  return result.rowsAffected;
}

