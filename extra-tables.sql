TABLESPACE USERS;

-- Primary Key
ALTER TABLE PM.PM_TODO ADD (
  CONSTRAINT PM_TODO_PK PRIMARY KEY (TODO_ID)
  USING INDEX TABLESPACE USERS
  ENABLE VALIDATE);

-- Status check constraint
ALTER TABLE PM.PM_TODO ADD (
  CONSTRAINT PM_TODO_STATUS_CHK
  CHECK (STATUS IN ('TODO','DONE','REVIEWED')));

-- Autonumber trigger
CREATE OR REPLACE TRIGGER PM.PM_TODO_TRG
BEFORE INSERT ON PM.PM_TODO
REFERENCING NEW AS New OLD AS Old
FOR EACH ROW
BEGIN
  :new.TODO_ID := PM.TODO_SEQ.NEXTVAL;
END PM_TODO_TRG;
