CREATE TABLE PM.PM_CP_FILE (
  FILE_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CP_ID        NUMBER NOT NULL
               REFERENCES PM.PM_CONSTRUCTION_PROCESS (ID) ON DELETE CASCADE,
  FILE_NAME    VARCHAR2(255) NOT NULL,
  FILE_TYPE    VARCHAR2(100),
  FILE_SIZE    NUMBER,
  FILE_DATA    BLOB,
  UPLOADED_BY  NUMBER,
  UPLOAD_DATE  DATE DEFAULT SYSDATE
);

CREATE INDEX PM.PM_CP_FILE_CP_IX ON PM.PM_CP_FILE (CP_ID);