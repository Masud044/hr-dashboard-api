-- Selection forms, areas, items and attached files
-- A form with no P_ID is a reusable template

CREATE TABLE PM.PM_SELECTION_FORM (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    P_ID            NUMBER,
    TITLE           VARCHAR2(200) NOT NULL,
    LEVEL_NO        VARCHAR2(20),
    IS_TEMPLATE     CHAR(1) DEFAULT 'N'
                      CHECK (IS_TEMPLATE IN ('Y', 'N')),
    STATUS          VARCHAR2(20) DEFAULT 'DRAFT'
                      CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'CONFIRMED')),
    COPIED_FROM_ID  NUMBER,
    PUBLISHED_DATE  DATE,
    PUBLISHED_BY    NUMBER,
    CONFIRMED_DATE  DATE,
    CONFIRMED_BY    NUMBER,
    CREATED_BY      NUMBER,
    CREATED_DATE    DATE DEFAULT SYSDATE,
    UPDATED_BY      NUMBER,
    UPDATED_DATE    DATE DEFAULT SYSDATE
);

CREATE INDEX IDX_PSF_PID ON PM.PM_SELECTION_FORM (P_ID);

CREATE TABLE PM.PM_SELECTION_AREA (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID      NUMBER NOT NULL
                   REFERENCES PM.PM_SELECTION_FORM (ID) ON DELETE CASCADE,
    PARENT_ID    NUMBER
                   REFERENCES PM.PM_SELECTION_AREA (ID) ON DELETE CASCADE,
    NAME         VARCHAR2(200) NOT NULL,
    FIELDS_JSON  CLOB,
    SORT_ORDER   NUMBER DEFAULT 0
);

CREATE INDEX IDX_PSA_FORM ON PM.PM_SELECTION_AREA (FORM_ID);

CREATE TABLE PM.PM_SELECTION_ITEM (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AREA_ID             NUMBER NOT NULL
                          REFERENCES PM.PM_SELECTION_AREA (ID) ON DELETE CASCADE,
    VALUES_JSON         CLOB,
    CUSTOMER_CONFIRMED  CHAR(1) DEFAULT 'N'
                          CHECK (CUSTOMER_CONFIRMED IN ('Y', 'N')),
    CUSTOMER_NOTE       VARCHAR2(1000),
    SORT_ORDER          NUMBER DEFAULT 0
);

CREATE INDEX IDX_PSI_AREA ON PM.PM_SELECTION_ITEM (AREA_ID);

CREATE TABLE PM.PM_SELECTION_FILE (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ITEM_ID       NUMBER NOT NULL
                    REFERENCES PM.PM_SELECTION_ITEM (ID) ON DELETE CASCADE,
    FIELD_KEY     VARCHAR2(100),
    FILE_NAME     VARCHAR2(255),
    MIME_TYPE     VARCHAR2(100),
    FILE_SIZE     NUMBER,
    DOC_FILE      BLOB,
    CREATED_BY    NUMBER,
    CREATED_DATE  DATE DEFAULT SYSDATE
);

CREATE INDEX IDX_PSFL_ITEM ON PM.PM_SELECTION_FILE (ITEM_ID);
