-- Selection note history kept each time a selection form is reopened

CREATE TABLE PM.PM_SELECTION_NOTE_HISTORY (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ITEM_ID     NUMBER NOT NULL
                  REFERENCES PM.PM_SELECTION_ITEM (ID) ON DELETE CASCADE,
    ROUND_NO    NUMBER NOT NULL,
    NOTE        VARCHAR2(1000),
    SAVED_BY    NUMBER,
    SAVED_DATE  DATE DEFAULT SYSDATE
);

CREATE INDEX IDX_PSNH_ITEM ON PM.PM_SELECTION_NOTE_HISTORY (ITEM_ID);
