-- Multiple contractors / dependents per PM_CONSTRUCTION_PROCESS line

CREATE TABLE PM_CP_CONTRACTOR (
    ASSIGNMENT_ID  NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CP_ID          NUMBER NOT NULL
                     REFERENCES PM_CONSTRUCTION_PROCESS (ID) ON DELETE CASCADE,
    CONTRACTOR_ID  NUMBER NOT NULL,
    ASSIGNED_BY    NUMBER NOT NULL,
    ASSIGNED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UNIQUE (CP_ID, CONTRACTOR_ID)
);

CREATE INDEX IDX_PCC_CONTRACTOR ON PM_CP_CONTRACTOR (CONTRACTOR_ID);

CREATE TABLE PM_CP_DEPENDENT (
    ASSIGNMENT_ID  NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CP_ID          NUMBER NOT NULL
                     REFERENCES PM_CONSTRUCTION_PROCESS (ID) ON DELETE CASCADE,
    DEPENDENT_ID   NUMBER NOT NULL,
    ASSIGNED_BY    NUMBER NOT NULL,
    ASSIGNED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UNIQUE (CP_ID, DEPENDENT_ID)
);

CREATE INDEX IDX_PCD_DEPENDENT ON PM_CP_DEPENDENT (DEPENDENT_ID);

-- copy existing single values into the new tables
INSERT INTO PM_CP_CONTRACTOR (CP_ID, CONTRACTOR_ID, ASSIGNED_BY)
SELECT ID, CONTRACTOR_ID, NVL(UPDATED_BY, NVL(CREATION_BY, 0))
  FROM PM_CONSTRUCTION_PROCESS
 WHERE CONTRACTOR_ID IS NOT NULL;

INSERT INTO PM_CP_DEPENDENT (CP_ID, DEPENDENT_ID, ASSIGNED_BY)
SELECT ID, DEPENDENT_ID, NVL(UPDATED_BY, NVL(CREATION_BY, 0))
  FROM PM_CONSTRUCTION_PROCESS
 WHERE DEPENDENT_ID IS NOT NULL;