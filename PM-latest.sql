BEFORE INSERT
ON PM.PM_CONSTRUCTION_PROCESS  REFERENCING NEW AS New OLD AS Old
FOR EACH ROW
begin
  select  CONSTRUCTION_PROCESS_SEQ.nextval into :new.ID  from dual;
end;
/


